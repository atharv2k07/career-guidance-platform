"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import AppNav from "@/components/AppNav";
import { fetchStudent, getStudentId, sampleProfile, type Student } from "@/lib/profile";
import { getCareer, recommend, skillSuggestions } from "@/lib/careers";

const chip = "rounded-full bg-indigo-50 px-3 py-1 text-xs font-medium text-indigo-700";

interface Rec { title: string; description: string; outlook: string; score: number; reason: string; missing_skills: string[] }

export default function Dashboard() {
  const [student, setStudent] = useState<Student | null>(null);
  const [recs, setRecs] = useState<Rec[]>([]);
  const [isSample, setIsSample] = useState(false);
  const [loadError, setLoadError] = useState("");

  useEffect(() => {
    const showSample = () => {
      setStudent(sampleProfile);
      setRecs(recommend(sampleProfile));
      setIsSample(true);
    };
    const id = getStudentId();
    if (!id) return showSample();
    fetchStudent(id)
      .then((d) => {
        if (!d) return showSample();
        setStudent(d.student);
        setRecs(d.recommendations.map((r) => ({ ...r, title: r.career_title })));
      })
      .catch((e) => {
        setLoadError(e instanceof Error ? e.message : "Could not load your profile");
        showSample();
      });
  }, []);

  // Content loads after the page, so jump to #recommendations / #skills once it exists.
  useEffect(() => {
    if (student && recs.length && window.location.hash) {
      document.getElementById(window.location.hash.slice(1))?.scrollIntoView();
    }
  }, [student, recs]);

  if (!student || recs.length === 0) return <AppNav />;

  const topCareer = getCareer(recs[0].title);
  const suggestions = topCareer ? skillSuggestions(student, topCareer) : [];
  const initials = student.full_name.split(" ").map((n) => n[0]).slice(0, 2).join("").toUpperCase();

  return (
    <>
      <AppNav />
      <main className="mx-auto max-w-6xl px-6 py-10">
        {isSample && (
          <div className="mb-6 rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-800">
            {loadError ? `Couldn't load your saved profile (${loadError}). ` : ""}Showing sample data. <Link href="/onboarding" className="font-semibold underline">Complete your profile</Link> to get personalized results.
          </div>
        )}

        <h1 className="text-3xl font-extrabold tracking-tight">
          Welcome back, {student.full_name.split(" ")[0]} 👋
        </h1>
        <p className="mt-2 text-slate-600">Here are the career paths that best fit your profile.</p>

        <div className="mt-8 grid gap-6 lg:grid-cols-3">
          {/* Profile summary */}
          <aside className="rounded-2xl border border-slate-200 p-6 lg:col-span-1">
            <div className="flex items-center gap-4">
              <div className="flex h-12 w-12 items-center justify-center rounded-full bg-indigo-600 font-bold text-white">{initials}</div>
              <div>
                <p className="font-semibold">{student.full_name}</p>
                <p className="text-xs text-slate-500">{student.email}</p>
              </div>
            </div>
            <dl className="mt-5 space-y-3 text-sm">
              <div><dt className="text-slate-500">College</dt><dd className="font-medium">{student.college}</dd></div>
              <div><dt className="text-slate-500">Branch · Year</dt><dd className="font-medium">{student.branch} · Year {student.year_of_study}</dd></div>
              <div><dt className="text-slate-500">Career goal</dt><dd className="font-medium">{student.career_goal}</dd></div>
              <div>
                <dt className="text-slate-500">Skills</dt>
                <dd className="mt-1 flex flex-wrap gap-2">{student.skills.map((s) => <span key={s} className={chip}>{s}</span>)}</dd>
              </div>
              <div>
                <dt className="text-slate-500">Interests</dt>
                <dd className="mt-1 flex flex-wrap gap-2">{student.interests.map((s) => <span key={s} className="rounded-full bg-slate-100 px-3 py-1 text-xs font-medium text-slate-700">{s}</span>)}</dd>
              </div>
            </dl>
            <Link href="/onboarding" className="mt-6 block rounded-lg border border-slate-300 py-2 text-center text-sm font-medium text-slate-700 hover:bg-slate-50">
              Edit profile
            </Link>
          </aside>

          {/* Recommendations */}
          <section id="recommendations" className="scroll-mt-24 space-y-4 lg:col-span-2">
            <h2 className="text-xl font-bold">Recommended career paths</h2>
            <p className="text-sm text-slate-500">Generated by our demo matching engine from your skills, interests, career goal and branch.</p>
            {recs.map((r, i) => (
              <div key={r.title} className="rounded-2xl border border-slate-200 p-6">
                <div className="flex items-start justify-between gap-4">
                  <div>
                    <span className="text-xs font-semibold text-indigo-600">#{i + 1} MATCH · {r.outlook}</span>
                    <h3 className="mt-1 text-lg font-semibold">{r.title}</h3>
                  </div>
                  <span className="text-2xl font-extrabold text-indigo-600">{r.score}%</span>
                </div>
                <div className="mt-3 h-2 rounded-full bg-slate-100">
                  <div className="h-2 rounded-full bg-indigo-500" style={{ width: `${r.score}%` }} />
                </div>
                <p className="mt-3 text-sm text-slate-600">{r.description}</p>
                <p className="mt-2 rounded-lg bg-slate-50 p-3 text-sm text-slate-600">💬 {r.reason}</p>
                {r.missing_skills?.length > 0 && (
                  <div className="mt-3 flex flex-wrap items-center gap-2 text-xs text-slate-500">
                    Skills to build:
                    {r.missing_skills.map((m) => <span key={m} className="rounded-full bg-amber-50 px-3 py-1 font-medium capitalize text-amber-800">{m}</span>)}
                  </div>
                )}
              </div>
            ))}
          </section>
        </div>

        {/* Skill development */}
        <section id="skills" className="mt-10 scroll-mt-24">
          <h2 className="text-xl font-bold">Skill development for {recs[0].title}</h2>
          <div className="mt-4 grid gap-4 sm:grid-cols-2">
            {suggestions.length ? suggestions.map((s) => (
              <div key={s.skill} className="rounded-xl border border-slate-200 p-5">
                <h3 className="font-semibold capitalize">{s.skill}</h3>
                <p className="mt-1 text-sm text-slate-600">{s.tip}</p>
              </div>
            )) : (
              <p className="text-sm text-slate-600">You already cover the core skills for your top match. Ask the mentor about advanced next steps.</p>
            )}
          </div>
        </section>

        {/* Mentor entry */}
        <section className="mt-10 rounded-2xl bg-indigo-600 p-8 text-center">
          <h2 className="text-2xl font-bold text-white">Have questions about your path?</h2>
          <p className="mx-auto mt-2 max-w-xl text-indigo-100">Chat with your AI mentor about roles, skill gaps and next steps.</p>
          <Link href="/mentor" className="mt-6 inline-block rounded-lg bg-white px-6 py-3 font-medium text-indigo-700 hover:bg-indigo-50">
            Talk to AI Mentor
          </Link>
        </section>
      </main>
    </>
  );
}
